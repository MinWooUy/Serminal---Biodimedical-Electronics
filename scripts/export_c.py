def c_array(name: str, ctype: str, arr: np.ndarray, lo: int, hi: int) -> str:
    a = np.asarray(arr, dtype=np.int64)
    if a.size and (a.min() < lo or a.max() > hi):
        raise OverflowError(f"{name}: values outside {ctype}")
    dims = "".join(f"[{s}]" for s in a.shape)

    def nest(x) -> str:                       # nested braces per dimension (C99, -Wmissing-braces clean)
        if x.ndim <= 1:
            return "{ " + ", ".join(str(int(v)) for v in np.atleast_1d(x)) + " }"
        return "{ " + ", ".join(nest(sub) for sub in x) + " }"
    body = nest(a) if a.ndim else str(int(a))
    return f"static const {ctype} {name}{dims} = {body};\n"


def weights_h_text(qm, pt, sos, delay: int, beats_cfg: dict) -> str:
    """Full text of weights.h for a quantised model (deterministic; used by export and by the DS2 check)."""
    I8, I32 = (-128, 127), (-2**31, 2**31 - 1)
    sq = quantize_sos(sos, FILTER_FRAC_BITS)
    lo, hi = (int(round(v * pt.fs)) for v in beats_cfg["rr_clip_s"])
    L = [
        "/* Auto-generated by scripts/export_c.py -- DO NOT EDIT. Integer constants of the deployed ECG pipeline.\n",
        " * Requantisation everywhere: y = (acc + (1 << (s - 1))) >> s with an ARITHMETIC shift on signed int\n",
        " * (s > 0), y = acc for s == 0, y = acc << -s for s < 0; ReLU + saturation = clamp(y, 0, 127).\n",
        " * round_div(a, b) = floor((2a + b) / (2b)) for b > 0 (round half up, also for negative a). */\n",
        "#ifndef ECG_WEIGHTS_H\n#define ECG_WEIGHTS_H\n#include <stdint.h>\n\n",
        f"#define FS {pt.fs}\n",
        "/* 0.5-40 Hz band-pass: 2 DF1 biquads, rows (b0, b1, b2, a0, a1, a2) in Q20; input (adc - adc_zero) << GUARD;\n"
        "   y = rshift_round(b0 x0 + b1 x1 + b2 x2 - a1 y1 - a2 y2, FRAC); accumulator int64, operands int32 */\n",
        f"#define FILTER_FRAC_BITS {FILTER_FRAC_BITS}\n#define FILTER_GUARD_BITS {FILTER_GUARD_BITS}\n"
        f"#define FILTER_DELAY {delay}\n",
        c_array("FILTER_SOS", "int32_t", sq, *I32),
        "\n/* Pan-Tompkins (integer, see python/dsp/pan_tompkins.py) */\n",
        f"#define PT_LP_LEN {pt.lp_len}\n#define PT_HP_LEN {pt.hp_len}\n#define PT_HP_DELAY {pt.hp_delay}\n"
        f"#define PT_DERIV_SHIFT {pt.deriv_shift}\n#define PT_MWI_LEN {pt.mwi_len}\n#define PT_REFRACTORY {pt.refractory}\n"
        f"#define PT_TWAVE {pt.twave_window}\n#define PT_LEARN_LEN {pt.learn_len}\n#define PT_SETTLE {pt.settle}\n"
        f"#define PT_PEAK_CONFIRM {pt.peak_confirm}\n#define PT_SB_BUFFER {pt.sb_buffer}\n"
        f"#define PT_BP_DELAY {pt.bp_delay}\n#define PT_IRREGULAR_HALVING {int(pt.irregular_halving)}\n",
        "\n/* beat window, z-score and RR */\n",
        f"#define REALIGN_HALF 18\n#define WIN_HALF {beats_cfg['half_window']}\n#define INPUT_EXP {INPUT_EXP}\n"
        f"#define EPS_Q {EPS_Q}\n#define RR_CLIP_LO {lo}\n#define RR_CLIP_HI {hi}\n#define RR_AVG_N {beats_cfg['rr_avg_n']}\n",
        c_array("RR_EXP", "int8_t", qm.rr_exp, *I8),
        "\n/* CNN (Lite): conv 'same' zero padding, MaxPool(2) after blocks 0-2; shift[c] = k_c + a_in - a_out */\n",
    ]
    for i, c in enumerate(qm.convs):
        cout, cin, k = c["w_q"].shape
        L.append(f"#define CONV{i}_COUT {cout}\n#define CONV{i}_CIN {cin}\n#define CONV{i}_K {k}\n#define CONV{i}_POOL {int(c['pool'])}\n")
        L.append(c_array(f"CONV{i}_W", "int8_t", c["w_q"], *I8))
        L.append(c_array(f"CONV{i}_B", "int32_t", c["b_q"], *I32))
        L.append(c_array(f"CONV{i}_SHIFT", "int8_t", c["k"] + c["a_in"] - c["a_out"], *I8))
    f1, f2 = qm.fc1, qm.fc2
    H, C = f1["wg_q"].shape
    L += [
        "\n/* FC1: acc = rshift_round(sum(WG * gap_sum), SHIFT_G) + rshift_round(sum(WR * rr_q), SHIFT_R) + B;\n"
        "   h = clamp(rshift_round(acc, SHIFT_OUT), 0, 127). gap_sum = int32 sum over the 45 positions. */\n",
        f"#define FC1_OUT {H}\n#define FC1_GAP_IN {C}\n#define FC1_RR_IN {f1['wr_q'].shape[1]}\n",
        c_array("FC1_WG", "int8_t", f1["wg_q"], *I8), c_array("FC1_WR", "int8_t", f1["wr_q"], *I8),
        c_array("FC1_B", "int32_t", f1["b_q"], *I32),
        c_array("FC1_SHIFT_G", "int8_t", f1["Eg"] - f1["E"], *I8),
        c_array("FC1_SHIFT_R", "int8_t", f1["Er"] - f1["E"], *I8),
        c_array("FC1_SHIFT_OUT", "int8_t", f1["E"] - f1["a_out"], *I8),
        "\n/* FC2: logits = sum(W * h) + B (int32, common scale) -> argmax: 0 N, 1 S, 2 V, 3 F */\n",
        f"#define FC2_OUT {f2['w_q'].shape[0]}\n",
        c_array("FC2_W", "int8_t", f2["w_q"], *I8), c_array("FC2_B", "int32_t", f2["b_q"], *I32),
        "\n#endif /* ECG_WEIGHTS_H */\n",
    ]
    return "".join(L)


def write_weights_h(path: Path, qm, pt, sos, delay: int, beats_cfg: dict) -> None:
    path.write_bytes(weights_h_text(qm, pt, sos, delay, beats_cfg).encode("ascii"))


def pick_segment(rec, seconds: float) -> int:
    n = int(seconds * rec.fs)
    non_n = np.zeros(len(rec.signal), dtype=np.int64)
    np.add.at(non_n, rec.r_samples[rec.aami > 0], 1)
    c = np.concatenate([[0], np.cumsum(non_n)])
    step = rec.fs * 10
    starts = np.arange(0, len(rec.signal) - n, step)
    return int(starts[np.argmax(c[starts + n] - c[starts])])


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--final-lite", required=True)
    ap.add_argument("--out", default="export")
    ap.add_argument("--records", default=",".join(map(str, DEFAULT_RECORDS)))
    ap.add_argument("--seconds", type=float, default=120.0)
    args = ap.parse_args()
    fl = Path(args.final_lite)
    qm = load_quant_model(fl / "lite_int8.npz")
    cfg = load_config(fl / "config.yaml")
    bcfg = load_config(REPO_ROOT / cfg["beats_config"])
    det_cfg = load_config(REPO_ROOT / bcfg["detector_config"])
    pt, sos = detector_from_config(det_cfg)
    delay = group_delay_compensation(sos, pt.fs)
    half = int(bcfg["beats"]["half_window"])
    lo, hi = (int(round(v * pt.fs)) for v in bcfg["beats"]["rr_clip_s"])
    out = REPO_ROOT / args.out
    gold = out / "golden"
    gold.mkdir(parents=True, exist_ok=True)
    write_weights_h(out / "weights.h", qm, pt, sos, delay, bcfg["beats"])
    manifest = {"model": str(fl.name), "segments": [], "notes": __doc__}
    total = {"beats": 0, "labels": {}}

    def put(seg: str, name: str, arr: np.ndarray, dtype: str, meaning: str) -> None:
        a = np.asarray(arr)
        info = np.iinfo(dtype)
        if a.size and (a.min() < info.min or a.max() > info.max):
            raise OverflowError(f"{seg}/{name} does not fit {dtype}")
        fn = f"{seg}_{name}.bin"
        a.astype("<" + np.dtype(dtype).str[1:]).tofile(gold / fn)
        manifest["segments"][-1]["arrays"][name] = {"file": fn, "dtype": dtype, "shape": list(a.shape),
                                                    "meaning": meaning}

    for rid in [int(r) for r in args.records.split(",")]:
        if rid not in DS1:
            raise SystemExit("golden vectors use DS1 records only")
        rec = load_record(rid)
        start = pick_segment(rec, args.seconds)
        n = int(args.seconds * rec.fs)
        adc = rec.adc[start:start + n].astype(np.int64)
        res = detect_offline(adc, rec.adc_zero, rec.adc_gain, pt, sos, return_stages=True)
        y_int = filter_int(adc, rec.adc_zero, sos)
        ib = run_integer_beats(y_int, res.r_coarse, delay, half, lo, hi)
        order, r_int, bi = ib["order"], ib["r_int"], ib["beat_index"]
        r_coarse = res.r_coarse[order]
        sb = np.array([res.detections[i].searchback for i in order], dtype=np.int8)
        windows, parts, z_q = ib["windows"], ib["rr_parts"], ib["z_q"]
        rr_q = quantise_rr_parts(parts, qm.rr_exp)
        tr = int_forward_trace(qm, z_q, rr_q)
        # labels: one-to-one matching with the segment's annotations (+-150 ms), VF excluded
        ann = rec.r_samples - start
        keep = (ann >= 0) & (ann < n)
        ann, aami = ann[keep], rec.aami[keep]
        vf = rec.vf_segments - start
        ka, kd = outside_vf(ann, vf), outside_vf(r_int[bi], vf)
        m = match_beats(ann[ka], r_int[bi][kd], tol_samples(150, pt.fs))
        label = np.full(len(bi), -2, dtype=np.int64)
        label[np.flatnonzero(kd)[m.pairs[:, 1]]] = aami[np.flatnonzero(ka)[m.pairs[:, 0]]]
        seg = f"rec{rid}_{start}"
        manifest["segments"].append({"name": seg, "record": rid, "start_sample": start, "n_samples": n,
                                     "adc_zero": rec.adc_zero, "n_detections": int(len(r_int)),
                                     "n_beats": int(len(bi)), "arrays": {}})
        st = res.stages
        put(seg, "adc", adc, "int16", "raw ADC counts (segment start = zero state everywhere)")
        put(seg, "pt_hp", st["hp"], "int32", "Pan-Tompkins band-pass (LP+HP) output per sample")
        put(seg, "pt_d", st["d"], "int32", "Pan-Tompkins derivative output per sample")
        put(seg, "pt_mwi", st["mwi"], "int32", "Pan-Tompkins MWI output per sample")
        put(seg, "filt", y_int, "int32", "0.5-40 Hz filter output, ADC * 2^12 (Q20 coefficients, int64 acc)")
        put(seg, "det_r_coarse", r_coarse, "int32", "detections: band-pass peak - 38 (sorted)")
        put(seg, "det_searchback", sb, "int8", "1 if the detection came from search-back")
        put(seg, "det_r_refined", r_int, "int32", "integer abs refinement on filt (+-18 samples, delay 2)")
        put(seg, "beat_det_index", bi, "int32", "index into the detections of each classified beat")
        put(seg, "beat_window", windows, "int32", "filt[R + 2 - 180 : R + 2 + 180]")
        put(seg, "beat_z_q", z_q, "int8", "integer z-score, scale 2^4, saturated +-127")
        put(seg, "beat_rr_parts", parts, "int32", "rr_prev, rr_next, sum of up to 8 past RR, count (samples, clipped 72..1080)")
        put(seg, "beat_rr_q", rr_q, "int8", "quantised RR features with RR_EXP")
        for key in ("conv0", "pool0", "conv1", "pool1", "conv2", "pool2", "conv3"):
            put(seg, f"beat_{key}", tr[key], "int8", f"CNN {key} output (after requantise / ReLU / saturate)")
        put(seg, "beat_gap", tr["gap"], "int32", "GAP sum over 45 positions")
        put(seg, "beat_fc1", tr["fc1"], "int8", "FC1 output")
        put(seg, "beat_logits", tr["logits"], "int32", "FC2 logits (common scale)")
        put(seg, "beat_pred", tr["logits"].argmax(1), "int8", "argmax: 0 N, 1 S, 2 V, 3 F")
        put(seg, "beat_label", label, "int8", "AAMI label of the matched annotation (-1 Q, -2 unmatched)")
        total["beats"] += int(len(bi))
        for v, c in zip(*np.unique(label, return_counts=True)):
            total["labels"][str(int(v))] = total["labels"].get(str(int(v)), 0) + int(c)
        print(f"{seg}: {len(r_int)} detections, {len(bi)} beats, labels "
              f"{dict(zip(*[x.tolist() for x in np.unique(label, return_counts=True)]))}, "
              f"pred agree with label {np.mean(tr['logits'].argmax(1)[label >= 0] == label[label >= 0]):.3f}")
    manifest["total"] = total
    import hashlib
    for s in manifest["segments"]:
        for a in s["arrays"].values():
            a["sha256"] = hashlib.sha256((gold / a["file"]).read_bytes()).hexdigest()
    text = json.dumps(manifest, indent=2)
    (gold / "manifest.json").write_bytes(text.encode("utf-8"))
    (out / "golden_manifest.json").write_bytes(text.encode("utf-8"))     # versioned copy (golden/*.bin are not); LF
    # self-check: every .bin reads back to the declared shape and type
    for s in manifest["segments"]:
        for name, a in s["arrays"].items():
            back = np.fromfile(gold / a["file"], dtype="<" + np.dtype(a["dtype"]).str[1:])
            assert back.size == int(np.prod(a["shape"])), (s["name"], name)
    print(f"total beats {total['beats']}, labels {total['labels']} -> {gold}; weights -> {out / 'weights.h'}")


if __name__ == "__main__":
    main()
