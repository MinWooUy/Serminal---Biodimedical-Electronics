"""Export for the C / RISC-V port: weights.h + golden vectors of the fully integer pipeline (DS1 only).

weights.h : every integer constant of the deployed pipeline (filter Q20 coefficients, Pan-Tompkins
            parameters, beat/RR constants, int8 CNN weights, int32 biases, per-channel shifts).
golden/   : contiguous DS1 ADC segments; each segment is processed FROM ZERO STATE (as the C code will):
  per sample : adc (int16), pt_hp / pt_d / pt_mwi (int32), filt (int32, ADC * 2^12)
  detections : r_coarse, searchback flag, r_refined (integer abs refinement)
  per beat   : r, window (int32 x 360, filtered), z_q (int8 x 360), rr_parts (rr_prev, rr_next, sum8, n8),
               rr_q (int8 x 4), conv0..3 (int8, before pooling), pool0..2, gap (int32), fc1 (int8),
               logits (int32 x 4), pred, label (AAMI 0..3, -1 Q, -2 unmatched detection)
  Raw little-endian .bin files + manifest.json (dtype, shape, meaning, SHA-256); a copy of the manifest is
  written to export/golden_manifest.json (versioned; the .bin files are reproducible and not versioned). The C port must match ALL
  of them bit-exactly (Week 3 requirement); float results are irrelevant for this check.
Segments: for each chosen record the window of --seconds with the most non-N annotated beats.
"""

